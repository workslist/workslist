import { isValidNumberInput, isValidCCVInput } from '../validacion';

  // Валидация номера карты пропускает корректный номер карты.
  test('Валидация номера карты пропускает корректный номер карты', () => {
    expect(isValidNumberInput('4111111111111111')).toBe(true);
  });

  // Валидация номера карты не пропускает произвольную строку, содержащую любые нецифровые символы. Для этого добавьте в валидируемую строку как минимум символы кириллицы, латиницы, знаки препинания.
  test('Валидация номера карты не пропускает произвольную строку', () => {
    expect(isValidNumberInput('411111111dфы_fd111')).toBe(false);
  });

  // Валидация номера карты не пропускает строку с недостаточным количеством цифр.
  test('Валидация номера карты не пропускает строку с недостаточным количеством цифр', () => {
    expect(isValidNumberInput('411111')).toBe(false);
  });

  // Валидация номера карты не пропускает строку со слишком большим количеством цифр (например, 25).
  test('Валидация номера карты не пропускает строку со слишком большим количеством цифр (например, 25).', () => {
    expect(isValidNumberInput('411111411111411111411111')).toBe(false);
  });

  // Валидация CVV/CVC пропускает строку с тремя цифровыми символами.
  test('Валидация CVV/CVC пропускает строку с тремя цифровыми символами.', () => {
    expect(isValidCCVInput('411')).toBe(true);
  });

  // Валидация CVV/CVC не пропускает строки с 1-2 цифровыми символами.
  test('Валидация CVV/CVC не пропускает строки с 1-2 цифровыми символами.', () => {
    expect(isValidCCVInput('41')).toBe(false);
  });

  // Валидация CVV/CVC не пропускает строки с 4+ цифровыми символами.
  test('Валидация CVV/CVC не пропускает строки с 4+ цифровыми символами.', () => {
    expect(isValidCCVInput('4141')).toBe(false);
  });

  // Валидация CVV/CVC не пропускает строки с тремя нецифровыми символами (латиница, кириллица и знаки препинания).
  test('Валидация CVV/CVC не пропускает строки с тремя нецифровыми символами (латиница, кириллица и знаки препинания).', () => {
    expect(isValidCCVInput('aч,')).toBe(false);
  });